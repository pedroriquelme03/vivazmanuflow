-- Só as UHs da Vivaz (as áreas e o Aquamania ficam de fora).
CREATE TEMP TABLE uhs_vivaz ON COMMIT DROP AS
SELECT a.id, a.numero
FROM public.gov_acomodacoes a
JOIN public.propriedades p ON p.id = a.propriedade_id AND p.nome ILIKE '%vivaz%'
WHERE a.tipo IN ('suite', 'apartamento');

UPDATE public.gov_acomodacoes a
SET categoria = coalesce(a.categoria, d.categoria),
    acomodacao = coalesce(a.acomodacao, d.acomodacao),
    permite_pet = d.permite_pet
FROM planilha_uhs d
JOIN uhs_vivaz u ON u.numero = d.numero
WHERE a.id = u.id;

INSERT INTO public.gov_local_itens (local_id, tipo_item_id, marca, modelo)
SELECT u.id, t.id, i.marca, i.modelo
FROM planilha_itens i
JOIN uhs_vivaz u ON u.numero = i.numero
JOIN public.gov_tipos_item t ON lower(t.nome) = lower(i.tipo)
WHERE NOT EXISTS (SELECT 1 FROM public.gov_local_itens x WHERE x.local_id = u.id);

-- Confere: UHs da planilha que não existem no cadastro (cadastre em Locais e rode de novo).
SELECT d.numero AS uh_nao_encontrada
FROM planilha_uhs d
WHERE NOT EXISTS (SELECT 1 FROM uhs_vivaz u WHERE u.numero = d.numero)
ORDER BY d.numero;
